from ament_index_python.packages import get_package_share_path

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration


def generate_launch_description():
    pkg_share = get_package_share_path('bunker_mini_description')
    # The maize field world and its plant/heightmap models live in the
    # Hunter SE package; both robots share them.
    field_share = get_package_share_path('hunter_se_description')

    world_arg = DeclareLaunchArgument(
        name='world', default_value=str(field_share / 'worlds/maize_field.sdf'),
        description='Maize field world generated by virtual_maize_field')
    headless_arg = DeclareLaunchArgument(
        name='headless', default_value='false', choices=['true', 'false'],
        description='Run the Gazebo server without its GUI')
    rviz_arg = DeclareLaunchArgument(
        name='rviz', default_value='false', choices=['true', 'false'],
        description='Start RViz')

    # Same start pose as the Hunter SE: in the headland, facing down the first row
    pose_args = [
        DeclareLaunchArgument(name=name, default_value=default,
                              description=f'Spawn pose of the robot: {name}')
        for name, default in (('x', '0.8094'), ('y', '-8.5386'), ('z', '0.65'),
                              ('yaw', '1.5658'))]

    forwarded = ('world', 'headless', 'rviz', 'x', 'y', 'z', 'yaw')
    gazebo = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(str(pkg_share / 'launch/gazebo.launch.py')),
        launch_arguments={
            **{name: LaunchConfiguration(name) for name in forwarded},
            'model_path': str(field_share / 'models'),
        }.items())

    return LaunchDescription([
        world_arg,
        headless_arg,
        rviz_arg,
        *pose_args,
        gazebo,
    ])
